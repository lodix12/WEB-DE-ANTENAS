function buildLocalNameExpr(): ExpressionSpecification {
  return [
    'coalesce',
    ['get', 'name'],
    ['get', 'name:es'],
    ['get', 'name:latin'],
    ['get', 'name_en'],
  ];
}

function hasAnyLabelFilter(): ExpressionSpecification {
  return [
    'any',
    ['has', 'name'],
    ['has', 'name:es'],
    ['has', 'name:latin'],
    ['has', 'name_en'],
  ];
}

function isSurfaceLineFilter(
  extra: ExpressionSpecification,
): ExpressionSpecification {
  return [
    'all',
    ['==', ['geometry-type'], 'LineString'],
    ['!=', ['get', 'brunnel'], 'tunnel'],
    ['!=', ['get', 'brunnel'], 'bridge'],
    extra,
  ];
}

function isTunnelLineFilter(
  extra: ExpressionSpecification,
): ExpressionSpecification {
  return [
    'all',
    ['==', ['geometry-type'], 'LineString'],
    ['==', ['get', 'brunnel'], 'tunnel'],
    extra,
  ];
}

function isBridgeLineFilter(
  extra: ExpressionSpecification,
): ExpressionSpecification {
  return [
    'all',
    ['==', ['geometry-type'], 'LineString'],
    ['==', ['get', 'brunnel'], 'bridge'],
    extra,
  ];
}

function buildRoadWidthExpr(
  stops: readonly RoadWidthStop[],
  base = 1.4,
): DataDrivenPropertyValueSpecification<number> {
  const args: unknown[] = ['interpolate', ['exponential', base], ['zoom']];
  for (let i = 0; i < stops.length; i++) {
    const [zoom, mainWidth, linkWidth] = stops[i];
    args.push(zoom);
    if (linkWidth !== undefined) {
      args.push(['case', ['==', ['get', 'ramp'], 1], linkWidth, mainWidth]);
    } else {
      args.push(mainWidth);
    }
  }
  return args as DataDrivenPropertyValueSpecification<number>;
}

